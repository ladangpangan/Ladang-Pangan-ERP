// =====================================================================
// ONE-TIME BACKFILL: seed HPP (cost/kg) onto EXISTING stock & Sales Order allocations
// from the product master "Harga Modal / HPP" (products.basePrice).
// -------------------------------------------------------------------
// WHY: opening stock entered via manual Tally Inbound (and the Sales Orders already built
// from it) were recorded with hpp_per_kg = 0 because, at the time, getProductHpp() did not
// read the product master price. This corrects that historical data so existing SO invoices
// show the real HPP / gross profit. Going forward, getProductHpp() now falls back to base_price
// so new inbound/SO already carry the correct cost.
//
// WHAT: runs ONCE (guarded by a mongo_migration marker). Operates DIRECTLY on the MongoDB
// (authoritative) collections BEFORE the per-request hydration, so every replica's SQLite mirror
// picks up the corrected values on its next full-replace hydrate. Only touches rows whose
// hpp_per_kg is 0/missing AND whose product has base_price > 0 (idempotent, never overwrites a
// real cost). Downstream (SO gross profit is computed live; COGS journals are regenerated by
// syncLedger) therefore corrects itself automatically.
//
// FIELD NAMING: master data collection `products` uses camelCase + `_id` (basePrice, _id),
// while transaction collections use snake_case + `id` (hpp_per_kg, product_id).
// =====================================================================
import { getMongoDb } from '@/lib/db/mongo';

const MARKER = 'hpp_backfill_from_baseprice_v1';
let _done = false; // per-pod cache: once confirmed applied, stop hitting Mongo.

export async function ensureHppBackfill() {
  if (_done) return;
  try {
    const db = getMongoDb();
    const meta = db.collection('mongo_migration');
    const m = await meta.findOne({ key: MARKER });
    if (m?.done) { _done = true; return; }

    // productId -> base_price (only > 0). products master is camelCase + _id.
    const bp = {};
    const products = await db.collection('products').find({}, { projection: { _id: 1, basePrice: 1 } }).toArray();
    for (const p of products) { const v = Number(p.basePrice || 0); if (v > 0) bp[p._id] = v; }

    const isZero = (x) => x === 0 || x === null || x === undefined;

    // inventory_stock: snake_case + id.
    let invUpdated = 0;
    const invOps = [];
    const stocks = await db.collection('inventory_stock').find({}, { projection: { id: 1, product_id: 1, hpp_per_kg: 1 } }).toArray();
    for (const st of stocks) {
      const v = bp[st.product_id];
      if (v && isZero(st.hpp_per_kg)) invOps.push({ updateOne: { filter: { id: st.id }, update: { $set: { hpp_per_kg: v } } } });
    }
    if (invOps.length) { await db.collection('inventory_stock').bulkWrite(invOps, { ordered: false }); invUpdated = invOps.length; }

    // so_item_stocks (SO stock allocations): snake_case + id + product_id.
    let soUpdated = 0;
    const soOps = [];
    const allocs = await db.collection('so_item_stocks').find({}, { projection: { id: 1, product_id: 1, hpp_per_kg: 1 } }).toArray();
    for (const a of allocs) {
      const v = bp[a.product_id];
      if (v && isZero(a.hpp_per_kg)) soOps.push({ updateOne: { filter: { id: a.id }, update: { $set: { hpp_per_kg: v } } } });
    }
    if (soOps.length) { await db.collection('so_item_stocks').bulkWrite(soOps, { ordered: false }); soUpdated = soOps.length; }

    await meta.updateOne({ key: MARKER }, { $set: { key: MARKER, done: true, at: Date.now(), invUpdated, soUpdated } }, { upsert: true });
    _done = true;
    console.log(`[hpp-backfill] applied from product.base_price -> inventory_stock=${invUpdated}, so_item_stocks=${soUpdated} rows corrected.`);
  } catch (e) {
    // Non-fatal: leave marker unset so it retries on a later request.
    console.error('[hpp-backfill] failed (will retry):', e?.message || e);
  }
}
